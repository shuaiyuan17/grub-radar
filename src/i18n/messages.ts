const zhMinutes = (m: number) => {
  const total = Math.max(1, Math.round(m));
  if (total < 60) return `${total} 分钟`;
  const h = Math.floor(total / 60);
  const rest = total % 60;
  return rest === 0 ? `${h} 小时` : `${h} 小时 ${rest} 分`;
};

